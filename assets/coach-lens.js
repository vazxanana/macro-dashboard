// what the trade context keeps (ctx.lens): short and plain
const ctxOf = (r, side) => (r && r.ok ? { edge: r.edge, name: r.name, state: String(r.state || '').slice(0, 160), agree: agree(r, side), signal: !!r.signal } : null);
